import { METRICS, formatMetric, type Comparison } from '@perfagent/core'

const ICON = { better: '✅', worse: '❌', same: '➖' }

/** Markdown for a pull-request comment, built client-side from the comparison. */
export function comparisonToMarkdown(c: Comparison): string {
  const [a, b] = c.sources
  const lines = [
    `## PerfAgent compare: ${a?.label ?? 'A'} → ${b?.label ?? 'B'}`,
    '',
    `**Score ${c.verdict.scoreFrom} → ${c.verdict.scoreTo}.** ${c.verdict.sentences.join(' ')}`,
    '',
  ]
  if (c.warnings.length) lines.push(...c.warnings.map((w) => `> ⚠️ ${w}`), '')
  lines.push('| Metric | Page | Before | After | Change |', '|---|---|---|---|---|')
  for (const d of c.diffs) {
    const before = d.from === undefined ? '—' : formatMetric(d.metric, d.from)
    const after = d.to === undefined ? '—' : formatMetric(d.metric, d.to)
    lines.push(`| ${METRICS[d.metric].short} | ${d.route} | ${before} | ${after} | ${ICON[d.direction]} ${d.label} |`)
  }
  const impact = c.impact.filter((i) => i.kind !== 'unknown')
  if (impact.length) {
    lines.push('', '### Where is the impact?', '')
    for (const i of impact) {
      const where = i.issue?.location ? ` (\`${i.issue.location.file}:${i.issue.location.line}\`)` : ''
      lines.push(`- **${labelFor(i.kind)}:** ${i.plain}${where}${i.effect ? ` · ${i.effect}` : ''}`)
    }
  }
  if (c.nextSteps.length) lines.push('', '### What to do next', '', ...c.nextSteps.map((s, i) => `${i + 1}. ${s}`))
  lines.push('', '_Generated by PerfAgent. Differences inside run-to-run noise are reported as "No real change"._')
  return lines.join('\n')
}

function labelFor(kind: Comparison['impact'][number]['kind']): string {
  return { fixed: 'Fixed', new: 'New problem', 'still-open': 'Still open', request: 'New download', unknown: 'Unknown' }[kind]
}
